// Helper methods to resolve graph relationships
exports.getDestinationsByState = (stateId) => 
  destinations.filter(d => d.stateId === stateId);

exports.getAreasByDestination = (destId) => 
  areas.filter(a => a.destinationId === destId);

exports.getPlacesByDestination = (destId) => 
  places.filter(p => p.destinationId === destId);

exports.getPlacesByArea = (areaId) => 
  places.filter(p => p.areaId === areaId);

exports.getToursByDestination = (destId) => 
  tours.filter(t => t.destinations.includes(destId));

exports.getToursByState = (stateId) => {
  const destIds = getDestinationsByState(stateId).map(d => d.id);
  return tours.filter(t => t.destinations.some(dId => destIds.includes(dId)));
};

